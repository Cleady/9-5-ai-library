/**
 * MAD101 STUDIO — BUNDLE BUILD SCRIPT
 * scripts/build.js
 * 
 * Đóng gói toàn bộ mã nguồn mô-đun trong js/ thành file app.bundle.js duy nhất.
 * Tương thích 100% với giao thức file:/// (mở trực tiếp không cần server, zero CORS).
 */

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const ROOT_DIR = path.resolve(__dirname, '..');
const JS_DIR = path.join(ROOT_DIR, 'js');
const OUTPUT_BUNDLE = path.join(ROOT_DIR, 'app.bundle.js');

console.log("==================================================================");
console.log("   MAD101 STUDIO — BUNDLER & ENGINE BUILDER");
console.log("==================================================================");

// 1. Chạy Quality Gate Validator trước
console.log("\n[1/3] Chạy Cổng chặn chất lượng (v2/validate.js)...");
try {
  execSync('node v2/validate.js', { stdio: 'inherit', cwd: ROOT_DIR });
} catch (e) {
  console.error("\n❌ LỖI BUILD: Cổng chặn chất lượng v2/validate.js thất bại. Hủy quy trình build!");
  process.exit(1);
}

// 2. Thứ tự các file nguồn theo cây phụ thuộc
const SOURCE_FILES = [
  'store.js',
  'router.js',
  'mathjax-render.js',
  'data.js',
  'screens/home.js',
  'screens/setup.js',
  'screens/quiz.js',
  'screens/result.js',
  'screens/history.js',
  'screens/settings.js',
  'app.js'
];

console.log("\n[2/3] Đang nạp và xử lý các file nguồn từ js/...");
let bundleBody = [];

SOURCE_FILES.forEach(relPath => {
  const fullPath = path.join(JS_DIR, relPath);
  if (!fs.existsSync(fullPath)) {
    console.error(`❌ Không tìm thấy file nguồn: ${relPath}`);
    process.exit(1);
  }

  let code = fs.readFileSync(fullPath, 'utf8');

  // Xóa các dòng import
  code = code.replace(/^\s*import\s+[^;]+;\s*$/gm, '');

  // Xóa từ khóa export đứng đầu biến/hàm/lớp
  code = code.replace(/^\s*export\s+(async\s+function|function|const|let|var|class)\s+/gm, '$1 ');

  // Xóa export { ... }
  code = code.replace(/^\s*export\s*\{[^}]+\};\s*$/gm, '');

  bundleBody.push(`
  /* ===================================================================
     SOURCE MODULE: js/${relPath}
     =================================================================== */
  ${code.trim()}
  `);
  console.log(`  ✓ Đã ghép: js/${relPath}`);
});

const bundleHeader = `/**
 * MAD101 STUDIO — BUNDLED APPLICATION SCRIPT
 * app.bundle.js
 * 
 * Auto-generated by scripts/build.js
 * Source directory: js/
 * Timestamp: ${new Date().toISOString()}
 * 
 * Works 100% offline and when directly double-clicking index.html (file:/// protocol).
 * Zero CORS errors, zero framework dependencies, instantaneous rendering.
 */

(function () {
  'use strict';
`;

const bundleFooter = `
})();
`;

const finalBundleContent = bundleHeader + bundleBody.join('\n\n') + bundleFooter;

fs.writeFileSync(OUTPUT_BUNDLE, finalBundleContent, 'utf8');
console.log(`\n[3/3] Đã ghi app.bundle.js (${(fs.statSync(OUTPUT_BUNDLE).size / 1024).toFixed(1)} KB)`);

// Kiểm tra cú pháp
try {
  execSync(`node --check "${OUTPUT_BUNDLE}"`, { cwd: ROOT_DIR });
  console.log("  ✓ Kiểm tra cú pháp node --check: HỢP LỆ 100%");
} catch (e) {
  console.error("❌ Cú pháp app.bundle.js có lỗi:", e.message);
  process.exit(1);
}

console.log("\n==================================================================");
console.log("✅ BUILD THÀNH CÔNG: app.bundle.js đã sẵn sàng!");
console.log("==================================================================\n");
